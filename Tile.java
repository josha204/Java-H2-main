public class Tile {
    private String tileId;

    public Tile(String tileId) {
        this.tileId = tileId;
    }

 // GETTERS
    // Get Tile Id
    public String getTileId() {
        return tileId;
    }

 // SETTERS
    // Set Tile Id
    public void setTileId(String tileId) {
        this.tileId = tileId;
    }
}